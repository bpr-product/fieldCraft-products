import fieldcraftLogo from "../../../assets/login/fieldcraftlogo.svg";
import { Building, BlueprintResponse, FacetEdgeMetrics, RoofFacet, RoofMetrics } from "./types";
import { computeTotals } from "./store/rooflensStore";

const ZERO_EDGES: FacetEdgeMetrics = {
  ridge_ft: 0, hip_ft: 0, valley_ft: 0, rake_ft: 0, eave_ft: 0, parapet_ft: 0,
};

const DISCLAIMER =
  "Decision-support estimate — not a quote, survey, or warranty. Generated by FIELDCRAFT RoofLens for internal planning; not validated against an on-site survey. Experimental / internal use only.";

const esc = (s: unknown): string =>
  String(s ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c] as string));

/** One facet in the export: geometry + editable per-facet edge sub-measurements. */
export interface FacetExport {
  facet_id: string;
  building_id: string;
  building_name: string;
  roof_area_sqft: number;
  footprint_sqft: number;
  pitch: string;
  perimeter_ft: number;
  source: string;
  /** Per-facet edge-length breakdown (feet), reflecting any manual edits in the UI. */
  edge_metrics: FacetEdgeMetrics;
  boundary_latlng: [number, number][];
}

export interface BuildingSummary {
  total_roof_area_sqft: number;
  facet_count: number;
  total_edge_length_ft: number;
  footprint_sqft: number;
}

/** One building/structure with its own facets, totals and Auto-Detect roof report. */
export interface BuildingExport {
  building_id: string;
  building_name: string;
  summary: BuildingSummary;
  /** EagleView-style roof report from the last Auto-Detect run for this building. */
  roof_report: RoofMetrics | null;
  facets: FacetExport[];
}

export interface RoofLensExportData {
  product: string;
  generated: string;
  experimental: true;
  note: string;
  address: string;
  country: string;
  lat: number | null;
  lng: number | null;
  summary: BuildingSummary & { building_count: number };
  /** Per-building breakdown (house, detached garage, …). */
  buildings: BuildingExport[];
  /** Flattened facets across all buildings (kept for the PDF path + compatibility). */
  facets: FacetExport[];
}

/** Build the export row for one facet, pulling in its edited edge sub-measurements. */
function facetExport(
  facet: RoofFacet,
  measurement: { label: string; roofAreaSqft: number; footprintSqft: number; perimeterFt: number; pitch: string; source: string },
  buildingName: string
): FacetExport {
  return {
    facet_id: measurement.label,
    building_id: facet.buildingId,
    building_name: buildingName,
    roof_area_sqft: Math.round(measurement.roofAreaSqft),
    footprint_sqft: Math.round(measurement.footprintSqft),
    pitch: measurement.pitch,
    perimeter_ft: Math.round(measurement.perimeterFt),
    source: measurement.source,
    edge_metrics: facet.edgeMetrics ?? ZERO_EDGES,
    boundary_latlng: facet.path.map((p) => [p.lat, p.lng] as [number, number]),
  };
}

/**
 * Build the full RoofLens export payload — all buildings, all facets, each
 * facet's editable edge sub-measurements, and each building's Auto-Detect roof
 * report. Values reflect the current UI state (including manual edits).
 */
export function buildExportData(
  address: string,
  country: string,
  lat: number | null,
  lng: number | null,
  buildings: Building[],
  allFacets: RoofFacet[],
  metricsByBuilding: Record<string, RoofMetrics | null>
): RoofLensExportData {
  const buildingExports: BuildingExport[] = buildings.map((b) => {
    const bFacets = allFacets.filter((f) => f.buildingId === b.id);
    const bTotals = computeTotals(bFacets);
    return {
      building_id: b.id,
      building_name: b.name,
      summary: {
        total_roof_area_sqft: Math.round(bTotals.totalRoofAreaSqft),
        facet_count: bTotals.facetCount,
        total_edge_length_ft: Math.round(bTotals.perimeterFt),
        footprint_sqft: Math.round(bTotals.footprintSqft),
      },
      roof_report: metricsByBuilding[b.id] ?? null,
      facets: bTotals.facets.map((m, i) => facetExport(bFacets[i], m, b.name)),
    };
  });

  const overall = computeTotals(allFacets);
  const flatFacets = buildingExports.flatMap((b) => b.facets);

  return {
    product: "FIELDCRAFT RoofLens",
    generated: new Date().toISOString(),
    experimental: true,
    note: DISCLAIMER,
    address,
    country,
    lat,
    lng,
    summary: {
      total_roof_area_sqft: Math.round(overall.totalRoofAreaSqft),
      facet_count: overall.facetCount,
      total_edge_length_ft: Math.round(overall.perimeterFt),
      footprint_sqft: Math.round(overall.footprintSqft),
      building_count: buildings.length,
    },
    buildings: buildingExports,
    facets: flatFacets,
  };
}

export function exportJson(data: RoofLensExportData): void {
  const blob = new Blob([JSON.stringify(data, null, 2)], { type: "application/json" });
  const name =
    "rooflens_" + (data.address || "measurement").replace(/[^a-z0-9]+/gi, "_").slice(0, 40) + ".json";
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/** Open a branded, self-contained print window (Save as PDF). */
export function exportPdf(data: RoofLensExportData, blueprint?: BlueprintResponse | null): void {
  const logoUrl = `${window.location.origin}${fieldcraftLogo}`;
  const dateStr = new Date(data.generated).toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });
  const coords = data.lat != null && data.lng != null ? `${data.lat.toFixed(6)}, ${data.lng.toFixed(6)}` : "";

  const ft = (v?: number): string => (typeof v === "number" && v > 0 ? `${Math.round(v).toLocaleString()} ft` : "—");
  const sqft = (v?: number): string => (typeof v === "number" ? `${Math.round(v).toLocaleString()} sq ft` : "—");
  // Show the Parapet column only if some facet actually has one (flat roofs).
  const anyParapet = data.facets.some((f) => (f.edge_metrics?.parapet_ft ?? 0) > 0);

  // EagleView-style roof report (per building), from the last Auto-Detect run.
  const roofReport = (rr: RoofMetrics | null): string => {
    if (!rr) return "";
    const items: [string, string][] = [
      ["Predominant pitch", rr.predominant_pitch ?? "—"],
      ["Ridges / Hips", ft((rr.ridge_ft ?? 0) + (rr.hip_ft ?? 0))],
      ["Valleys", ft(rr.valley_ft)],
      ["Rakes", ft(rr.rake_ft)],
      ["Eaves", ft(rr.eave_ft)],
      ...((rr.parapet_ft ?? 0) > 0 ? ([["Parapets", ft(rr.parapet_ft)]] as [string, string][]) : []),
      ["Est. attic", sqft(rr.estimated_attic_sqft)],
      ["Stories", rr.stories != null ? String(rr.stories) : rr.number_of_stories ?? "—"],
      ["Building height", ft(rr.building_height_ft)],
      ["Complexity", rr.structure_complexity ?? "—"],
    ];
    return (
      `<div class="report">` +
      items.map(([k, v]) => `<div class="ri"><div class="rk">${esc(k)}</div><div class="rv">${esc(v)}</div></div>`).join("") +
      `</div>`
    );
  };

  // Per-facet table including the editable edge sub-measurements.
  const facetTable = (facets: RoofLensExportData["facets"]): string => {
    const head =
      `<tr><th>Facet</th><th>Roof area</th><th>Pitch</th>` +
      `<th>Ridge</th><th>Hip</th><th>Valley</th><th>Rake</th><th>Eave</th>` +
      (anyParapet ? `<th>Parapet</th>` : ``) +
      `</tr>`;
    const body = facets
      .map((f) => {
        const e = f.edge_metrics ?? { ridge_ft: 0, hip_ft: 0, valley_ft: 0, rake_ft: 0, eave_ft: 0, parapet_ft: 0 };
        return (
          `<tr><td>${esc(f.facet_id)}</td><td>${f.roof_area_sqft.toLocaleString()} sq ft</td><td>${esc(f.pitch)}</td>` +
          `<td>${ft(e.ridge_ft)}</td><td>${ft(e.hip_ft)}</td><td>${ft(e.valley_ft)}</td><td>${ft(e.rake_ft)}</td><td>${ft(e.eave_ft)}</td>` +
          (anyParapet ? `<td>${ft(e.parapet_ft)}</td>` : ``) +
          `</tr>`
        );
      })
      .join("");
    return `<table><thead>${head}</thead><tbody>${body}</tbody></table>`;
  };

  // One section per building: title, its roof report, then its facet table.
  const multiBuilding = data.buildings.length > 1;
  const buildingsBlock = data.buildings
    .map((b) => {
      const title = multiBuilding
        ? `${b.building_name} · ${b.summary.total_roof_area_sqft.toLocaleString()} sq ft · ${b.summary.facet_count} facets`
        : "Roof Report";
      return (
        `<div class="band">${esc(title)}</div>` +
        roofReport(b.roof_report) +
        `<div class="subband">Facet Measurements</div>` +
        facetTable(b.facets)
      );
    })
    .join("");

  // `src` comes from the external RoofLens gateway response and is written into a
  // (non-sandboxed) iframe via doc.write — so only emit an <img> for a recognized
  // image source AND escape it, so an attacker-influenced value can neither be an
  // unexpected scheme nor break out of the attribute.
  const SAFE_IMG_SRC = /^(?:data:image\/(?:png|jpe?g|gif|webp);base64,[A-Za-z0-9+/=\s]+|https:\/\/[^\s"'<>]+)$/i;
  const figure = (src?: string, title?: string): string =>
    src && SAFE_IMG_SRC.test(src)
      ? `<div class="diagram"><div class="diagram-title">${esc(title)}</div><img src="${esc(src)}" alt="${esc(title)}"/></div>`
      : "";
  const diagramBlock = blueprint
    ? figure(blueprint.aerial, "Aerial Top-Down View") +
      figure(blueprint.image, "Roof Diagram (Aerial + Facets)") +
      figure(blueprint.facets_only, "Facet Diagram")
    : `<div class="flag">Diagram images unavailable — measurements below are unaffected.</div>`;

  const html =
    `<!doctype html><html><head><meta charset="utf-8"><title>FIELDCRAFT RoofLens Report</title><style>` +
    `:root{--brand:#112D4E;--band:#E8EAF6;--muted:#5B6472;--rowalt:#F4F5FB;}` +
    `*{box-sizing:border-box;}body{font-family:Poppins,Arial,Helvetica,sans-serif;color:#1e2433;margin:0;padding:36px 40px 64px;}` +
    `.hdr{display:flex;align-items:center;justify-content:space-between;border-bottom:2px solid var(--brand);padding-bottom:10px;}` +
    `.hdr img{height:52px;width:auto;}.hdr .t{font-size:18px;font-weight:700;color:var(--brand);text-align:right;}` +
    `.hdr .s{font-size:10px;color:var(--muted);text-align:right;}` +
    `.addr{display:flex;justify-content:space-between;align-items:center;background:var(--brand);color:#fff;border-radius:4px;padding:9px 14px;margin:16px 0 6px;}` +
    `.addr .a{font-size:14px;font-weight:700;}.addr .r{font-size:11px;opacity:.92;}` +
    `.meta{font-size:11px;color:var(--muted);margin:0 2px 14px;}` +
    `.band{background:var(--band);border-left:4px solid var(--brand);color:var(--brand);font-size:12px;font-weight:700;text-transform:uppercase;padding:7px 12px;margin:16px 0 10px;border-radius:2px;}` +
    `.flag{background:#fff7ed;border:1px solid #fdba74;color:#9a3412;padding:9px 12px;border-radius:6px;font-size:11px;margin:12px 0;line-height:1.45;}` +
    `.tot{font-size:14px;margin:2px 0 12px;color:#334155;}.tot strong{font-size:22px;color:var(--brand);}` +
    `.report{display:flex;flex-wrap:wrap;gap:8px 22px;margin:6px 2px 12px;}` +
    `.ri{min-width:88px;}.rk{font-size:8.5px;text-transform:uppercase;letter-spacing:.3px;color:var(--muted);}` +
    `.rv{font-size:13px;font-weight:700;color:#1e2433;}` +
    `.subband{font-size:11px;font-weight:600;color:#334155;margin:10px 2px 4px;}` +
    `.diagram{margin:12px 0;text-align:center;page-break-inside:avoid;}.diagram-title{font-size:12px;font-weight:600;color:#334155;text-align:left;margin-bottom:6px;}` +
    `.diagram img{max-width:100%;border:1px solid #cbd5e1;border-radius:6px;}` +
    `table{border-collapse:collapse;width:100%;font-size:12px;}thead th{background:var(--brand);color:#fff;padding:7px 10px;text-align:left;}` +
    `tbody td{padding:6px 10px;border-bottom:1px solid #e6e8f2;}tbody tr:nth-child(even){background:var(--rowalt);}` +
    `.foot{position:fixed;bottom:0;left:0;right:0;padding:8px 40px;border-top:1px solid var(--brand);font-size:8px;color:var(--muted);display:flex;justify-content:space-between;background:#fff;}` +
    `.btn{margin-top:20px;padding:9px 18px;font-size:14px;background:var(--brand);color:#fff;border:none;border-radius:5px;cursor:pointer;}` +
    `@media print{.btn{display:none;}body{padding-bottom:48px;}}` +
    `</style></head><body>` +
    `<div class="hdr"><img src="${logoUrl}" alt="FIELDCRAFT"/><div><div class="t">Roof Measurement Report</div><div class="s">FIELDCRAFT Cloud · RoofLens</div><div class="s">${esc(dateStr)}</div></div></div>` +
    `<div class="addr"><span class="a">${esc(data.address || "Measured roof")}</span><span class="r">${esc(coords)}</span></div>` +
    `<div class="meta"><b>Generated:</b> ${esc(new Date(data.generated).toLocaleString())}</div>` +
    `<div class="flag">${esc(data.note)}</div>` +
    `<div class="tot"><strong>${data.summary.total_roof_area_sqft.toLocaleString()}</strong> sq ft total roof area &middot; ${data.summary.facet_count} facets &middot; ${data.summary.total_edge_length_ft.toLocaleString()} ft total edge length${data.summary.building_count > 1 ? ` &middot; ${data.summary.building_count} buildings` : ``}</div>` +
    `<div class="band">Roof Diagrams</div>${diagramBlock}` +
    buildingsBlock +
    `<div class="foot"><span>FIELDCRAFT RoofLens — decision-support only, not a quote or survey. Experimental / internal use.</span><span>FIELDCRAFT Cloud</span></div>` +
    `</body></html>`;

  // Render into a hidden iframe and print in-place — no new tab, no pop-up.
  const iframe = document.createElement("iframe");
  iframe.setAttribute("aria-hidden", "true");
  iframe.style.position = "fixed";
  iframe.style.right = "0";
  iframe.style.bottom = "0";
  iframe.style.width = "0";
  iframe.style.height = "0";
  iframe.style.border = "0";
  document.body.appendChild(iframe);

  const cleanup = () => {
    try { iframe.remove(); } catch { /* already removed */ }
  };
  const doc = iframe.contentWindow?.document;
  if (!doc) {
    cleanup();
    return;
  }
  doc.open();
  doc.write(html);
  doc.close();

  // Give the logo + diagram images a moment to load, then print in the iframe.
  window.setTimeout(() => {
    const win = iframe.contentWindow;
    if (!win) {
      cleanup();
      return;
    }
    win.focus();
    win.onafterprint = () => window.setTimeout(cleanup, 300);
    win.print();
    // Fallback cleanup if onafterprint never fires (some browsers).
    window.setTimeout(cleanup, 60000);
  }, 500);
}
